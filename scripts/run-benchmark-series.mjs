#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { aggregateRuns } from './aggregate-benchmark-runs.mjs';
import { scenarios } from '../benchmarks/scenarios.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RUNNER = path.join(REPO_ROOT, 'scripts', 'run-planner-benchmark.mjs');

function arg(name, fallback = null) {
  const index = process.argv.indexOf('--' + name);
  return index >= 0 ? process.argv[index + 1] : fallback;
}

function runChild(args, env) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [RUNNER, ...args], {
      cwd: REPO_ROOT, env, stdio: 'inherit', windowsHide: true
    });
    child.once('error', reject);
    child.once('close', (code, signal) => resolve({ code, signal }));
  });
}

function csvLines(source) {
  const lines = source.replace(/\r\n/g, '\n').split('\n');
  return { header: lines[0] || '', rows: lines.slice(1).filter(line => line.trim()) };
}

export async function runBenchmarkSeries({ runs = 3, outDir } = {}) {
  if (!Number.isInteger(runs) || runs < 3 || runs > 5) {
    throw new Error('--runs must be an integer from 3 to 5; three is the minimum certification sample');
  }
  if (process.env.OIOL_BENCHMARK_ALLOW_LIVE !== '1') {
    throw new Error('Set OIOL_BENCHMARK_ALLOW_LIVE=1 to explicitly authorize live provider calls.');
  }
  if (!process.env.OIOL_API_KEY && process.env.OIOL_PROVIDER !== 'ollama') {
    throw new Error('OIOL_API_KEY is required for the configured remote planning provider.');
  }
  const outputDir = path.resolve(outDir || path.join('benchmarks', 'results', 'series-' + new Date().toISOString().replaceAll(':', '-')));
  await fs.mkdir(outputDir, { recursive: true });

  const selectedIds = scenarios.map(item => item.id);
  if (selectedIds.length !== 10) throw new Error('The published planning benchmark must contain exactly ten scenarios.');
  const runFiles = [];
  const reviewFiles = [];
  const reviewPlanFiles = [];

  for (let index = 0; index < runs; index++) {
    const runFile = path.join(outputDir, 'run-' + String(index + 1).padStart(2, '0') + '.json');
    const reviewFile = runFile.replace(/\.json$/, '-human-review.csv');
    console.log('\n=== OIOL benchmark repetition ' + (index + 1) + ' of ' + runs + ' ===');
    const result = await runChild(['--scenarios', 'all', '--out', runFile], process.env);
    if (result.signal) throw new Error('Benchmark runner terminated by signal ' + result.signal);
    if (result.code !== 0 && result.code !== 2) throw new Error('Benchmark run ' + (index + 1) + ' failed before producing a complete result (exit ' + result.code + ').');
    const report = JSON.parse(await fs.readFile(runFile, 'utf8'));
    if (!Array.isArray(report.scores) || report.scores.length !== selectedIds.length) {
      throw new Error('Benchmark run ' + (index + 1) + ' did not produce one score row for all ten scenarios.');
    }
    runFiles.push(runFile);
    try {
      await fs.access(reviewFile);
      reviewFiles.push(reviewFile);
      const reviewPlanDir=runFile.replace(/\\.json$/,'-review-plans');
      const entries=await fs.readdir(reviewPlanDir);
      if(entries.length!==selectedIds.length) throw new Error('Blinded review plan packet is incomplete for repetition '+(index+1));
      reviewPlanFiles.push(...entries.map(name=>path.join(reviewPlanDir,name)));
    } catch {
      throw new Error('Human-review sheet was not produced for run ' + (index + 1));
    }
  }

  const runReports = await Promise.all(runFiles.map(async file => JSON.parse(await fs.readFile(file, 'utf8'))));
  const aggregate = aggregateRuns(runReports);
  const aggregatePath = path.join(outputDir, 'repeat-aggregate.json');
  await fs.writeFile(aggregatePath, JSON.stringify({
    ...aggregate,
    seriesProtocolVersion: '1.0.0',
    runFiles: runFiles.map(file => path.basename(file)),
    humanReviewFiles: reviewFiles.map(file => path.basename(file)),
    blindedReviewPlanFiles: reviewPlanFiles.map(file => path.relative(outputDir,file)),
    humanReviewStatus: 'pending_human_review',
    humanReviewRequiredPlans: runs * selectedIds.length,
    humanReviewRequiredRows: runs * selectedIds.length * 2,
    note: 'Automated medians and spreads do not replace blinded human review. No human score is generated by this runner.'
  }, null, 2) + '\n');

  const sheets = await Promise.all(reviewFiles.map(file => fs.readFile(file, 'utf8')));
  const parsed = sheets.map(csvLines);
  const header = parsed[0]?.header;
  if (!header || parsed.some(item => item.header !== header)) throw new Error('Human-review CSV headers differ between repetitions.');
  const consolidatedReviewPath = path.join(outputDir, 'human-review-all-runs.csv');
  await fs.writeFile(consolidatedReviewPath, [header, ...parsed.flatMap(item => item.rows)].join('\n') + '\n');

  console.log(JSON.stringify({
    runCount: aggregate.runCount,
    scenarioCount: aggregate.expectedScenarioCount,
    completeSuiteCoverage: aggregate.completeSuiteCoverage,
    failureRate: aggregate.failureRate,
    overallMedian: aggregate.runAverageScore.median,
    overallSpread: aggregate.runAverageScore.spread,
    scenarioMediansAndSpread: aggregate.scenarioResults.map(item => ({
      scenarioId: item.scenarioId, median: item.median, spread: item.spread, failedRuns: item.failedRuns
    })),
    outputDir, aggregatePath, consolidatedReviewPath,
    humanReviewStatus: 'pending_human_review',
    blindedReviewPlanCount: reviewPlanFiles.length
  }, null, 2));
  return { aggregate, outputDir, aggregatePath, consolidatedReviewPath };
}

export async function main() {
  const runs = Number(arg('runs', '3'));
  const outDir = arg('out-dir');
  const result = await runBenchmarkSeries({ runs, outDir });
  return result.aggregate.certificationReadyForHumanReview ? 0 : 2;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { process.exitCode = await main(); }
  catch (error) { console.error('Benchmark series error: ' + error.message); process.exitCode = 1; }
}
